DATASETS = {
    "goa": ("Goa Coastal District Real Road Network", GOA_ROADS),
    "mangaluru": ("Mangaluru Coastal District Real Road Network", MANGALURU_ROADS),
    "mumbai": ("Mumbai Harbor District Real Road Network", MUMBAI_ROADS),
}

def build_feature(r):
    return {
        "type": "Feature",
        "geometry": {
            "type": "LineString",
            "coordinates": r["coordinates"]
        },
        "properties": {
            "id": r["id"],
            "name": r["name"],
            "ref": r.get("ref", "NH"),
            "elevation_m": r["elevation_m"],
            "critical": r["critical"],
            "lanes": r["lanes"],
            "speed_limit_kmh": r.get("speed_limit_kmh", 60),
            "is_evacuation_corridor": r["is_evacuation_corridor"],
            "classification": r["classification"],
        }
    }

def main():
    for zid, (name, roads) in DATASETS.items():
        fc = {
            "type": "FeatureCollection",
            "meta": {
                "zone_id": zid,
                "name": name,
                "road_count": len(roads),
            },
            "features": [build_feature(r) for r in roads]
        }
        out_path = OUT_DIR / f"{zid}.geojson"
        out_path.write_text(json.dumps(fc, indent=2), encoding="utf-8")
        print(f"[OK] Wrote {len(roads)} verified roads to {out_path}")

if __name__ == "__main__":
    main()
